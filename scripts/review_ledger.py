#!/usr/bin/env python3
"""Assemble a code-review ledger from the agents' JSON outputs and the oracle runs.

Every number in the ledger is computed from the input files; nothing is typed by hand except
the conclusions, which are included verbatim from a separate file so that regenerating the
ledger never loses them.

    python scripts/review_ledger.py --module pyali/extract.py \\
        --findings docs/review/extract_pilot_findings.json \\
        --verdicts docs/review/extract_pilot_verdicts.json \\
        --junit /path/to/synthetic_junit.xml --real-metrics docs/review/extract_pilot_real_runs.json \\
        --mechanical /path/mechanical_ruff.txt /path/mechanical_ast.txt \\
        --agents docs/review/extract_pilot_agents.json \\
        --conclusions docs/review/extract_pilot_conclusions.md \\
        --out docs/review/extract_pilot.md

See ``docs/review/rubric.md`` for the finding and verdict schemas.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)

CATEGORY = {1: "index and convention crossings", 2: "MATLAB parity and numerics", 3: "degenerate inputs",
            4: "parameter-coupled invariants", 5: "shared mutable state and aliasing",
            6: "silent degradation", 7: "cross-module schema contracts", 8: "memory amplification",
            9: "doc and code drift"}
SEVERITIES = ("S1", "S2", "S3", "S4")
VERDICTS = ("CONFIRMED", "PLAUSIBLE", "REJECTED")


def _load(path, default):
    if path and os.path.isfile(path):
        with open(path) as f:
            return json.load(f)
    return default


def _git():
    try:
        out = subprocess.run(["git", "-C", _REPO, "log", "-1", "--format=%h %ad %s", "--date=short"],
                             capture_output=True, text=True, timeout=10).stdout.strip()
        dirty = subprocess.run(["git", "-C", _REPO, "status", "--porcelain"], capture_output=True,
                               text=True, timeout=10).stdout.strip()
        return out + (" (dirty)" if dirty else "")
    except Exception:                                           # a ledger must still build without git
        return "unknown"


def _junit(path):
    if not path or not os.path.isfile(path):
        return None
    root = ET.parse(path).getroot()
    suites = root.iter("testsuite") if root.tag == "testsuites" else [root]
    rows, totals = [], Counter()
    for s in suites:
        for tc in s.iter("testcase"):
            status = "passed"
            for child in tc:
                if child.tag in ("failure", "error"):
                    status = "failed"
                elif child.tag == "skipped":
                    status = "xfail" if "xfail" in (child.get("type") or "") or "expected" in (child.get("message") or "").lower() else "skipped"
            rows.append((tc.get("name"), status, float(tc.get("time") or 0)))
            totals[status] += 1
    return dict(rows=rows, totals=totals)


def _short(s, n=110):
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    return s if len(s) <= n else s[:n - 1] + "…"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", required=True)
    ap.add_argument("--findings", required=True)
    ap.add_argument("--verdicts", default=None)
    ap.add_argument("--junit", default=None)
    ap.add_argument("--real-metrics", default=None)
    ap.add_argument("--mechanical", nargs="*", default=[])
    ap.add_argument("--agents", default=None, help="json: [{name, role, wall_minutes, notes}]")
    ap.add_argument("--conclusions", default=None, help="markdown included verbatim at the end")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)

    F = _load(a.findings, {})
    V = _load(a.verdicts, {})
    findings = F.get("findings", [])
    verdicts = {v["id"]: v for v in V.get("verdicts", [])}
    agents = _load(a.agents, [])
    real = _load(a.real_metrics, [])
    junit = _junit(a.junit)

    L = []
    L.append(f"# Review ledger: `{a.module}`\n")
    L.append(f"Generated by `scripts/review_ledger.py` at commit {_git()}. Findings and verdicts are "
             f"copied from the agents' JSON; every count below is computed from those files. "
             f"Rubric: `docs/review/rubric.md`.\n")

    # ---- oracles
    L.append("## Oracles\n")
    if junit:
        t = junit["totals"]
        L.append("Synthetic suite (`tests/test_extract_oracle.py`): "
                 + ", ".join(f"{t[k]} {k}" for k in ("passed", "failed", "xfail", "skipped") if t[k])
                 + f"; {sum(r[2] for r in junit['rows']):.0f} s total.\n")
        L.append("| test | status | s |\n|---|---|---|")
        for name, status, sec in junit["rows"]:
            L.append(f"| `{name}` | {status} | {sec:.1f} |")
        L.append("")
    if real:
        L.append("Real data (256x256 crops of `133603_P-4_W-C2_443-2_443screen2_DIV35__burst47`, all frames, "
                 "profile 443screen2):\n")
        L.append("| run | window (row, col) | s | regions | cells | APs |\n|---|---|---|---|---|---|")
        for m in real:
            c = m.get("crop", {})
            L.append(f"| {m['label']} | ({c.get('row')}, {c.get('col')}) | {m['seconds']} | {m['n_regions']} | "
                     f"{m['n_cells']} | {m['n_aps']} |")
        L.append("")

    # ---- mechanical
    if a.mechanical:
        L.append("## Mechanical pass\n")
        for path in a.mechanical:
            if not os.path.isfile(path):
                continue
            text = open(path).read()
            L.append(f"<details><summary><code>{os.path.basename(path)}</code></summary>\n\n```\n{text.strip()}\n```\n</details>\n")

    # ---- findings
    L.append("## Findings\n")
    L.append(f"{len(findings)} reported by the reviewer; {len(verdicts)} with a verdict.\n")
    L.append("| id | function | line | cat | sev | reviewer conf. | verdict | claim | evidence |\n|---|---|---|---|---|---|---|---|---|")
    for f in findings:
        v = verdicts.get(f["id"], {})
        L.append(f"| {f['id']} | `{f.get('function')}` | {f.get('line')} | {f.get('category')} | {f.get('severity')} | "
                 f"{f.get('confidence', '')} | **{v.get('verdict', '—')}** | {_short(f.get('claim'), 140)} | "
                 f"{_short(v.get('evidence', ''), 140)} |")
    L.append("")
    for f in findings:
        v = verdicts.get(f["id"], {})
        L.append(f"<details><summary><b>{f['id']}</b> · {f.get('function')} · {f.get('severity')} · {v.get('verdict', 'no verdict')}</summary>\n")
        L.append(f"**Claim.** {f.get('claim')}\n\n**Failure scenario.** {f.get('failure_scenario')}\n")
        if f.get("reproducer_sketch"):
            L.append(f"**Reproducer (reviewer).**\n\n```\n{f['reproducer_sketch']}\n```\n")
        if v:
            L.append(f"**Verifier.** {v.get('verdict')} — {v.get('evidence')}\n")
            if v.get("command"):
                L.append(f"```\n{v['command']}\n```\n")
            if v.get("output"):
                L.append(f"```\n{_short(v['output'], 1200)}\n```\n")
        L.append("</details>\n")

    # ---- non-findings
    nf = F.get("non_findings", [])
    if nf:
        L.append("## Non-findings (checked and found sound)\n")
        L.append("| function | checked |\n|---|---|")
        for n in nf:
            L.append(f"| `{n.get('function')}` | {_short(n.get('checked'), 220)} |")
        L.append("")
    if F.get("notes"):
        L.append(f"**Reviewer notes.** {F['notes']}\n")
    if V.get("notes"):
        L.append(f"**Verifier notes.** {V['notes']}\n")

    # ---- metrics
    L.append("## Metrics (computed)\n")
    by_sev = Counter((f["severity"], verdicts.get(f["id"], {}).get("verdict", "none")) for f in findings)
    L.append("| severity | reported | confirmed | plausible | rejected |\n|---|---|---|---|---|")
    for s in SEVERITIES:
        rep = sum(1 for f in findings if f["severity"] == s)
        if rep:
            L.append(f"| {s} | {rep} | {by_sev[(s, 'CONFIRMED')]} | {by_sev[(s, 'PLAUSIBLE')]} | {by_sev[(s, 'REJECTED')]} |")
    tot = Counter(verdicts.get(f["id"], {}).get("verdict", "none") for f in findings)
    L.append(f"| **all** | {len(findings)} | {tot['CONFIRMED']} | {tot['PLAUSIBLE']} | {tot['REJECTED']} |\n")
    by_cat = Counter((int(f["category"]), verdicts.get(f["id"], {}).get("verdict", "none")) for f in findings)
    L.append("| category | reported | confirmed | plausible | rejected |\n|---|---|---|---|---|")
    for c in sorted(CATEGORY):
        rep = sum(1 for f in findings if int(f["category"]) == c)
        L.append(f"| {c} {CATEGORY[c]} | {rep} | {by_cat[(c, 'CONFIRMED')]} | {by_cat[(c, 'PLAUSIBLE')]} | {by_cat[(c, 'REJECTED')]} |")
    L.append("")
    if findings:
        surv = (tot["CONFIRMED"] + tot["PLAUSIBLE"]) / len(findings)
        L.append(f"Survival rate (confirmed + plausible) / reported: **{surv:.0%}**; strict (confirmed only): "
                 f"**{tot['CONFIRMED'] / len(findings):.0%}**.\n")
    if agents:
        L.append("| agent | role | wall minutes | notes |\n|---|---|---|---|")
        for g in agents:
            L.append(f"| {g.get('name')} | {g.get('role')} | {g.get('wall_minutes')} | {_short(g.get('notes'), 160)} |")
        L.append("")
    probes = F.get("probes", [])
    if probes:
        L.append(f"Reviewer probes run: {len(probes)}.\n")

    # ---- conclusions
    if a.conclusions and os.path.isfile(a.conclusions):
        L.append(open(a.conclusions).read().strip() + "\n")

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(L))
    print(f"[ledger] {a.out}: {len(findings)} findings, {len(verdicts)} verdicts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
